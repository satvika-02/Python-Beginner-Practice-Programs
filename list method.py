students = ["satvi", "manju", "lahari"]

print("Original List:", students)

# append()
students.append("satvi")
print("After append:", students)

# insert()
students.insert(1, "lahari")
print("After insert:", students)

# remove()
students.remove("manju")
print("After remove:", students)

# pop()
students.pop()
print("After pop:", students)

# sort()
students.sort()
print("After sort:", students)

# reverse()
students.reverse()
print("After reverse:", students)